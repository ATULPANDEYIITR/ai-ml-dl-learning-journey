-- Aggregation: cluster sizes and within-cluster error.
SELECT *
FROM clustering.cluster_report
WHERE model_id = 1
ORDER BY cluster_id;

-- CTE: rank K candidates by inertia and silhouette score.
WITH latest_evaluation AS (
    SELECT DISTINCT ON (k)
        k, inertia, silhouette_score, evaluation_notes
    FROM clustering.model_evaluations
    WHERE dataset_id = 1
    ORDER BY k, restart_seed DESC
)
SELECT
    k,
    inertia,
    silhouette_score,
    rank() OVER (ORDER BY inertia) AS inertia_rank,
    evaluation_notes
FROM latest_evaluation
ORDER BY k;

-- Inertia must not increase across recorded iterations of a standard
-- Lloyd K-Means run with unchanged data and no arbitrary reseeding.
SELECT
    model_id,
    iteration_number,
    inertia,
    inertia - lag(inertia) OVER (
        PARTITION BY model_id ORDER BY iteration_number
    ) AS inertia_change
FROM clustering.iteration_history
ORDER BY model_id, iteration_number;

-- Eligibility report: K must be supported by the number of observations.
SELECT
    m.model_id,
    m.model_name,
    m.k,
    count(o.observation_id) AS available_observations,
    m.k <= count(o.observation_id) AS valid_k,
    m.model_status,
    m.inertia
FROM clustering.models m
LEFT JOIN clustering.observations o ON o.dataset_id = m.dataset_id
GROUP BY m.model_id, m.model_name, m.k, m.model_status, m.inertia
ORDER BY m.model_id;

