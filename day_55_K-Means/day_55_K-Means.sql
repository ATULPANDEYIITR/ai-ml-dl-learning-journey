-- Retrieval: the persisted partition for each observation.
SELECT o.external_key, o.features, a.cluster_id, a.squared_distance
FROM clustering.observations o
JOIN clustering.assignments a USING (observation_id)
WHERE o.dataset_id = 1 AND a.model_id = 1
