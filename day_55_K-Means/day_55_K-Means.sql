-- K-Means clustering analytics in PostgreSQL.
-- The schema stores observations, model configurations, centroids,
-- assignments, iteration history, and K-selection experiments.
-- PostgreSQL 14+ is recommended.

BEGIN;

CREATE SCHEMA IF NOT EXISTS clustering;

CREATE TABLE IF NOT EXISTS clustering.datasets (
    dataset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_name TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL,
    feature_count INTEGER NOT NULL CHECK (feature_count > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS clustering.observations (
    observation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL
        REFERENCES clustering.datasets(dataset_id) ON DELETE CASCADE,
    external_key TEXT NOT NULL,
    features DOUBLE PRECISION[] NOT NULL,
    CHECK (cardinality(features) > 0),
    UNIQUE (dataset_id, external_key)
);

-- Reject NaN and infinities, inconsistent feature counts, and non-finite values.
CREATE OR REPLACE FUNCTION clustering.validate_observation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    expected_count INTEGER;
    feature_value DOUBLE PRECISION;
BEGIN
    SELECT feature_count
    INTO expected_count
    FROM clustering.datasets
    WHERE dataset_id = NEW.dataset_id;

    IF expected_count IS NULL THEN
        RAISE EXCEPTION 'Dataset % does not exist', NEW.dataset_id;
    END IF;

    IF cardinality(NEW.features) <> expected_count THEN
        RAISE EXCEPTION 'Expected % features, received %',
            expected_count, cardinality(NEW.features);
    END IF;

    FOREACH feature_value IN ARRAY NEW.features LOOP
        IF feature_value IS NULL
           OR feature_value = 'NaN'::DOUBLE PRECISION
           OR feature_value = 'Infinity'::DOUBLE PRECISION
           OR feature_value = '-Infinity'::DOUBLE PRECISION THEN
            RAISE EXCEPTION 'Features must be finite, non-null values';
        END IF;
    END LOOP;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS observations_validate ON clustering.observations;
CREATE TRIGGER observations_validate
BEFORE INSERT OR UPDATE OF dataset_id, features
ON clustering.observations
FOR EACH ROW
EXECUTE FUNCTION clustering.validate_observation();

CREATE TABLE IF NOT EXISTS clustering.models (
    model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL
        REFERENCES clustering.datasets(dataset_id) ON DELETE CASCADE,
    model_name TEXT NOT NULL,
    k INTEGER NOT NULL CHECK (k > 0),
    initialization TEXT NOT NULL
        CHECK (initialization IN ('random', 'kmeans++')),
    max_iterations INTEGER NOT NULL DEFAULT 300
        CHECK (max_iterations > 0),
    tolerance DOUBLE PRECISION NOT NULL DEFAULT 0.000001
        CHECK (tolerance >= 0 AND tolerance < 'Infinity'::DOUBLE PRECISION),
    random_seed INTEGER NOT NULL DEFAULT 42,
    restart_count INTEGER NOT NULL DEFAULT 5 CHECK (restart_count > 0),
    model_status TEXT NOT NULL DEFAULT 'configured'
        CHECK (model_status IN ('configured', 'running', 'completed', 'failed')),
    inertia DOUBLE PRECISION,
    iterations_completed INTEGER CHECK (iterations_completed IS NULL
        OR iterations_completed > 0),
    converged BOOLEAN,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (dataset_id, model_name),
    CHECK (inertia IS NULL OR
        (inertia >= 0 AND inertia < 'Infinity'::DOUBLE PRECISION))
);

CREATE INDEX IF NOT EXISTS models_dataset_k_idx
    ON clustering.models(dataset_id, k);

CREATE TABLE IF NOT EXISTS clustering.centroids (
    model_id BIGINT NOT NULL
        REFERENCES clustering.models(model_id) ON DELETE CASCADE,
    cluster_id INTEGER NOT NULL CHECK (cluster_id >= 0),
    coordinates DOUBLE PRECISION[] NOT NULL,
    PRIMARY KEY (model_id, cluster_id)
);

CREATE TABLE IF NOT EXISTS clustering.assignments (
    model_id BIGINT NOT NULL
        REFERENCES clustering.models(model_id) ON DELETE CASCADE,
    observation_id BIGINT NOT NULL
        REFERENCES clustering.observations(observation_id) ON DELETE CASCADE,
    cluster_id INTEGER NOT NULL CHECK (cluster_id >= 0),
    squared_distance DOUBLE PRECISION NOT NULL
        CHECK (squared_distance >= 0
           AND squared_distance < 'Infinity'::DOUBLE PRECISION),
    PRIMARY KEY (model_id, observation_id)
);

CREATE INDEX IF NOT EXISTS assignments_cluster_idx
    ON clustering.assignments(model_id, cluster_id);

CREATE TABLE IF NOT EXISTS clustering.iteration_history (
    model_id BIGINT NOT NULL
        REFERENCES clustering.models(model_id) ON DELETE CASCADE,
    iteration_number INTEGER NOT NULL CHECK (iteration_number > 0),
    inertia DOUBLE PRECISION NOT NULL
        CHECK (inertia >= 0 AND inertia < 'Infinity'::DOUBLE PRECISION),
    maximum_centroid_shift DOUBLE PRECISION NOT NULL
        CHECK (maximum_centroid_shift >= 0
           AND maximum_centroid_shift < 'Infinity'::DOUBLE PRECISION),
    PRIMARY KEY (model_id, iteration_number)
);

CREATE TABLE IF NOT EXISTS clustering.model_evaluations (
    dataset_id BIGINT NOT NULL
        REFERENCES clustering.datasets(dataset_id) ON DELETE CASCADE,
    k INTEGER NOT NULL CHECK (k > 0),
    restart_seed INTEGER NOT NULL,
    inertia DOUBLE PRECISION NOT NULL
        CHECK (inertia >= 0 AND inertia < 'Infinity'::DOUBLE PRECISION),
    silhouette_score DOUBLE PRECISION
        CHECK (silhouette_score IS NULL OR
               (silhouette_score >= -1 AND silhouette_score <= 1)),
    evaluation_notes TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (dataset_id, k, restart_seed)
);

-- Prevent a completed model from referencing nonexistent cluster numbers.
CREATE OR REPLACE FUNCTION clustering.validate_model_completion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    observation_count BIGINT;
    centroid_count BIGINT;
    assignment_count BIGINT;
    invalid_assignments BIGINT;
BEGIN
    IF NEW.model_status <> 'completed' THEN
        RETURN NEW;
    END IF;

    IF NEW.inertia IS NULL OR NEW.iterations_completed IS NULL
       OR NEW.converged IS NULL THEN
        RAISE EXCEPTION 'Completed models require inertia, iterations, and convergence state';
    END IF;

    SELECT count(*) INTO observation_count
    FROM clustering.observations
    WHERE dataset_id = NEW.dataset_id;

    IF observation_count = 0 THEN
        RAISE EXCEPTION 'Cannot complete a model for an empty dataset';
    END IF;

    IF NEW.k > observation_count THEN
        RAISE EXCEPTION 'K (%) exceeds observation count (%)',
            NEW.k, observation_count;
    END IF;

    SELECT count(*) INTO centroid_count
    FROM clustering.centroids
    WHERE model_id = NEW.model_id;

    IF centroid_count <> NEW.k THEN
        RAISE EXCEPTION 'Expected % centroids, found %', NEW.k, centroid_count;
    END IF;

    SELECT count(*) INTO assignment_count
    FROM clustering.assignments a
    JOIN clustering.observations o USING (observation_id)
    WHERE a.model_id = NEW.model_id
      AND o.dataset_id = NEW.dataset_id;

    IF assignment_count <> observation_count THEN
        RAISE EXCEPTION 'Every observation must have exactly one assignment';
    END IF;

    SELECT count(*) INTO invalid_assignments
    FROM clustering.assignments a
    WHERE a.model_id = NEW.model_id
      AND a.cluster_id >= NEW.k;

    IF invalid_assignments > 0 THEN
        RAISE EXCEPTION 'Assignments reference an invalid cluster';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS models_validate_completion ON clustering.models;
CREATE TRIGGER models_validate_completion
BEFORE INSERT OR UPDATE OF model_status, inertia, iterations_completed, converged
ON clustering.models
FOR EACH ROW
EXECUTE FUNCTION clustering.validate_model_completion();

-- The distance function assumes equal-length, finite feature vectors.
CREATE OR REPLACE FUNCTION clustering.squared_euclidean(
    a DOUBLE PRECISION[],
    b DOUBLE PRECISION[]
)
RETURNS DOUBLE PRECISION
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
    result DOUBLE PRECISION := 0;
    i INTEGER;
BEGIN
    IF cardinality(a) <> cardinality(b) THEN
        RAISE EXCEPTION 'Distance vectors have different dimensions';
    END IF;

    FOR i IN 1..cardinality(a) LOOP
        result := result + (a[i] - b[i]) * (a[i] - b[i]);
    END LOOP;

    RETURN result;
END;
$$;

-- Report cluster sizes and within-cluster sum of squared distances.
CREATE OR REPLACE VIEW clustering.cluster_report AS
SELECT
    m.model_id,
    m.model_name,
    m.k,
    a.cluster_id,
    count(*) AS observation_count,
    sum(a.squared_distance) AS cluster_inertia,
    avg(a.squared_distance) AS mean_squared_distance
FROM clustering.models m
JOIN clustering.assignments a ON a.model_id = m.model_id
WHERE m.model_status = 'completed'
GROUP BY m.model_id, m.model_name, m.k, a.cluster_id;

