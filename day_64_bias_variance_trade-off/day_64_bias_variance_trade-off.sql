-- ============================================================================
-- Bias-Variance Tradeoff: PostgreSQL Model Evaluation and Governance Workflow
--
-- Models:
--   dataset_profiles
--       -> experiment_runs
--           -> model_candidates
--               -> evaluation_metrics
--                   -> model_decisions
--
-- The evaluation records represent repeated experimental measurements.
-- This database does not train regression models. It stores and evaluates
-- metrics produced by a separate model-evaluation process.
--
-- Compatible with PostgreSQL 14+.
-- ============================================================================

BEGIN;

DROP SCHEMA IF EXISTS bias_variance_lab CASCADE;
CREATE SCHEMA bias_variance_lab;

SET search_path TO bias_variance_lab, public;

-- ============================================================================
-- 1. Dataset and experiment definitions
-- ============================================================================

CREATE TABLE dataset_profiles (
    dataset_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_name        TEXT NOT NULL UNIQUE,
    sample_size         INTEGER NOT NULL CHECK (sample_size >= 10),
    repetitions         INTEGER NOT NULL CHECK (repetitions BETWEEN 10 AND 10000),
    noise_stddev        NUMERIC(12, 6) NOT NULL CHECK (noise_stddev >= 0),
    signal_description  TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE experiment_policies (
    policy_id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_name                     TEXT NOT NULL UNIQUE,
    max_test_error_ratio            NUMERIC(8, 4) NOT NULL
        CHECK (max_test_error_ratio >= 1.0),
    underfit_train_error_ratio      NUMERIC(8, 4) NOT NULL
        CHECK (underfit_train_error_ratio >= 1.0),
    minimum_samples_per_parameter   NUMERIC(8, 4) NOT NULL
        CHECK (minimum_samples_per_parameter > 0),
    maximum_prediction_variance     NUMERIC(14, 8) NOT NULL
        CHECK (maximum_prediction_variance >= 0),
    created_at                      TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE experiment_runs (
    experiment_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id          BIGINT NOT NULL
        REFERENCES dataset_profiles(dataset_id),
    policy_id           BIGINT NOT NULL
        REFERENCES experiment_policies(policy_id),
    experiment_name     TEXT NOT NULL UNIQUE,
    state               TEXT NOT NULL DEFAULT 'DRAFT'
        CHECK (state IN ('DRAFT', 'RUNNING', 'COMPLETED', 'FAILED')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    started_at          TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ,
    failure_reason      TEXT,
    CHECK (
        (state = 'DRAFT' AND started_at IS NULL AND completed_at IS NULL)
        OR
        (state = 'RUNNING' AND started_at IS NOT NULL AND completed_at IS NULL)
        OR
        (state = 'COMPLETED' AND started_at IS NOT NULL AND completed_at IS NOT NULL)
        OR
        (state = 'FAILED' AND started_at IS NOT NULL AND completed_at IS NOT NULL)
    )
);

-- ============================================================================
-- 2. Candidate models and measured evaluation results
-- ============================================================================

CREATE TABLE model_candidates (
    candidate_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_family        TEXT NOT NULL
        CHECK (model_family IN ('POLYNOMIAL_RIDGE')),
    candidate_name      TEXT NOT NULL UNIQUE,
    polynomial_degree   INTEGER NOT NULL CHECK (polynomial_degree BETWEEN 0 AND 12),
    ridge_lambda        NUMERIC(14, 10) NOT NULL CHECK (ridge_lambda >= 0),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (model_family, polynomial_degree, ridge_lambda)
);

CREATE TABLE evaluation_metrics (
    evaluation_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id           BIGINT NOT NULL
        REFERENCES experiment_runs(experiment_id),
    candidate_id            BIGINT NOT NULL
        REFERENCES model_candidates(candidate_id),
    repetitions             INTEGER NOT NULL CHECK (repetitions >= 2),

    average_training_mse    NUMERIC(16, 10) NOT NULL
        CHECK (average_training_mse >= 0),

    bias_squared            NUMERIC(16, 10) NOT NULL
        CHECK (bias_squared >= 0),

    prediction_variance     NUMERIC(16, 10) NOT NULL
        CHECK (prediction_variance >= 0),

    irreducible_noise       NUMERIC(16, 10) NOT NULL
        CHECK (irreducible_noise >= 0),

    -- Expected noisy test error:
    -- bias_squared + prediction_variance + irreducible_noise.
    expected_test_mse       NUMERIC(17, 10)
        GENERATED ALWAYS AS (
            bias_squared + prediction_variance + irreducible_noise
        ) STORED,

    -- The difference between expected noisy test error and observed
    -- average training error is a descriptive generalization-gap estimate.
    generalization_gap      NUMERIC(17, 10)
        GENERATED ALWAYS AS (
            bias_squared
            + prediction_variance
            + irreducible_noise
            - average_training_mse
        ) STORED,

    recorded_at             TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    UNIQUE (experiment_id, candidate_id)
);

-- ============================================================================
-- 3. Model decisions
-- ============================================================================

CREATE TABLE model_decisions (
    decision_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id               BIGINT NOT NULL,
    candidate_id                BIGINT NOT NULL,
    risk_label                  TEXT NOT NULL
        CHECK (
            risk_label IN (
                'UNDERFITTING',
                'OVERFITTING',
                'GENERALIZES_WELL'
            )
        ),
    decision_status             TEXT NOT NULL
        CHECK (decision_status IN ('ACCEPTED', 'REJECTED')),
    samples_per_parameter       NUMERIC(12, 4) NOT NULL
        CHECK (samples_per_parameter > 0),
    best_expected_test_mse      NUMERIC(17, 10) NOT NULL
        CHECK (best_expected_test_mse >= 0),
    rationale                   TEXT NOT NULL,
    decided_at                  TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    FOREIGN KEY (experiment_id, candidate_id)
        REFERENCES evaluation_metrics(experiment_id, candidate_id),

    UNIQUE (experiment_id, candidate_id)
);

-- ============================================================================
-- 4. Performance-oriented indexes
-- ============================================================================

CREATE INDEX idx_experiment_runs_dataset_state
    ON experiment_runs(dataset_id, state);

CREATE INDEX idx_evaluation_metrics_experiment
    ON evaluation_metrics(experiment_id);

CREATE INDEX idx_evaluation_metrics_candidate
    ON evaluation_metrics(candidate_id);

CREATE INDEX idx_evaluation_metrics_expected_test
    ON evaluation_metrics(experiment_id, expected_test_mse);

CREATE INDEX idx_model_candidates_complexity
    ON model_candidates(model_family, polynomial_degree);

CREATE INDEX idx_model_decisions_status
    ON model_decisions(experiment_id, decision_status);

-- ============================================================================
-- 5. Integrity triggers
-- ============================================================================

CREATE OR REPLACE FUNCTION guard_experiment_state_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    decision_count BIGINT;
BEGIN
    IF NEW.state IS DISTINCT FROM OLD.state THEN
        IF NOT (
            (OLD.state = 'DRAFT' AND NEW.state = 'RUNNING')
            OR
            (OLD.state = 'RUNNING' AND NEW.state IN ('COMPLETED', 'FAILED'))
        ) THEN
            RAISE EXCEPTION
                'Invalid experiment transition: % -> %',
                OLD.state,
                NEW.state;
        END IF;
    END IF;

    IF NEW.state = 'COMPLETED' THEN
        SELECT COUNT(*)
        INTO decision_count
        FROM model_decisions
        WHERE experiment_id = NEW.experiment_id;

        IF decision_count = 0 THEN
            RAISE EXCEPTION
                'An experiment cannot complete without model decisions.';
        END IF;

        IF NEW.completed_at IS NULL THEN
            NEW.completed_at := clock_timestamp();
        END IF;
    END IF;

    IF NEW.state = 'FAILED' AND NEW.completed_at IS NULL THEN
        NEW.completed_at := clock_timestamp();
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_guard_experiment_state
BEFORE UPDATE OF state ON experiment_runs
FOR EACH ROW
EXECUTE FUNCTION guard_experiment_state_transition();


CREATE OR REPLACE FUNCTION guard_evaluation_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    current_state       TEXT;
    required_repetitions INTEGER;
BEGIN
    SELECT
        er.state,
        dp.repetitions
    INTO
        current_state,
        required_repetitions
    FROM experiment_runs er
    JOIN dataset_profiles dp
        ON dp.dataset_id = er.dataset_id
    WHERE er.experiment_id = NEW.experiment_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Experiment % does not exist.', NEW.experiment_id;
    END IF;

    IF current_state <> 'RUNNING' THEN
        RAISE EXCEPTION
            'Metrics can only be recorded for RUNNING experiments.';
    END IF;

    IF NEW.repetitions <> required_repetitions THEN
        RAISE EXCEPTION
            'Metric repetitions (%) must match dataset repetitions (%).',
            NEW.repetitions,
            required_repetitions;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_guard_evaluation_insert
BEFORE INSERT ON evaluation_metrics
FOR EACH ROW
EXECUTE FUNCTION guard_evaluation_insert();


