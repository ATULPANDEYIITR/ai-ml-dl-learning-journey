CREATE OR REPLACE VIEW v_evaluation_report AS
SELECT
    er.experiment_id,
    er.experiment_name,
    er.state AS experiment_state,
    dp.dataset_name,
    dp.sample_size,
    dp.repetitions,
    mc.candidate_name,
    mc.polynomial_degree,
    mc.ridge_lambda,
    em.average_training_mse,
    em.bias_squared,
    em.prediction_variance,
    em.irreducible_noise,
    em.expected_test_mse,
    em.generalization_gap,
    md.risk_label,
    md.decision_status,
    md.samples_per_parameter,
    md.rationale
FROM experiment_runs er
JOIN dataset_profiles dp
    ON dp.dataset_id = er.dataset_id
JOIN evaluation_metrics em
    ON em.experiment_id = er.experiment_id
JOIN model_candidates mc
    ON mc.candidate_id = em.candidate_id
LEFT JOIN model_decisions md
    ON md.experiment_id = em.experiment_id
   AND md.candidate_id = em.candidate_id;


CREATE OR REPLACE VIEW v_complexity_curve AS
SELECT
    er.experiment_id,
    mc.model_family,
    mc.polynomial_degree,
    COUNT(*) AS evaluation_count,
    ROUND(AVG(em.average_training_mse), 6) AS mean_training_mse,
    ROUND(AVG(em.bias_squared), 6) AS mean_bias_squared,
    ROUND(AVG(em.prediction_variance), 6) AS mean_prediction_variance,
    ROUND(AVG(em.expected_test_mse), 6) AS mean_expected_test_mse,
    ROUND(AVG(em.generalization_gap), 6) AS mean_generalization_gap
FROM experiment_runs er
JOIN evaluation_metrics em
    ON em.experiment_id = er.experiment_id
JOIN model_candidates mc
    ON mc.candidate_id = em.candidate_id
GROUP BY
    er.experiment_id,
    mc.model_family,
    mc.polynomial_degree;


-- ============================================================================
-- 7. Workflow processing functions and procedures
-- ============================================================================

CREATE OR REPLACE PROCEDURE start_experiment(
    p_experiment_id BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE experiment_runs
    SET
        state = 'RUNNING',
        started_at = clock_timestamp()
    WHERE experiment_id = p_experiment_id
      AND state = 'DRAFT';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Experiment % is missing or is not in DRAFT state.',
            p_experiment_id;
    END IF;
END;
$$;


CREATE OR REPLACE PROCEDURE complete_experiment(
    p_experiment_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    current_state TEXT;
    sample_count INTEGER;
    minimum_samples NUMERIC;
    maximum_test_ratio NUMERIC;
    underfit_train_ratio NUMERIC;
    maximum_variance NUMERIC;
    metric_count BIGINT;
BEGIN
    SELECT
        er.state,
        dp.sample_size,
        ep.minimum_samples_per_parameter,
        ep.max_test_error_ratio,
        ep.underfit_train_error_ratio,
        ep.maximum_prediction_variance
    INTO
        current_state,
        sample_count,
        minimum_samples,
        maximum_test_ratio,
        underfit_train_ratio,
        maximum_variance
    FROM experiment_runs er
    JOIN dataset_profiles dp
        ON dp.dataset_id = er.dataset_id
    JOIN experiment_policies ep
        ON ep.policy_id = er.policy_id
    WHERE er.experiment_id = p_experiment_id
    FOR UPDATE OF er;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Experiment % does not exist.', p_experiment_id;
    END IF;

    IF current_state <> 'RUNNING' THEN
        RAISE EXCEPTION
            'Only RUNNING experiments can be completed.';
    END IF;

    SELECT COUNT(*)
    INTO metric_count
    FROM evaluation_metrics
    WHERE experiment_id = p_experiment_id;

    IF metric_count = 0 THEN
        RAISE EXCEPTION
            'Cannot complete an experiment without evaluation metrics.';
    END IF;

    WITH experiment_statistics AS (
        SELECT
            em.experiment_id,
            em.candidate_id,
            em.average_training_mse,
            em.prediction_variance,
            em.expected_test_mse,
            mc.polynomial_degree,
            sample_count::NUMERIC /
                (mc.polynomial_degree + 1)::NUMERIC
                AS samples_per_parameter
        FROM evaluation_metrics em
        JOIN model_candidates mc
            ON mc.candidate_id = em.candidate_id
        WHERE em.experiment_id = p_experiment_id
    ),
    best_values AS (
        SELECT
            MIN(expected_test_mse) AS best_test_mse,
            MIN(average_training_mse) AS best_training_mse
        FROM experiment_statistics
    ),
    assessed AS (
        SELECT
            es.*,
            bv.best_test_mse,
            bv.best_training_mse,
            (
                es.expected_test_mse >
                bv.best_test_mse * maximum_test_ratio
            ) AS test_error_exceeds_limit,
            (
                es.average_training_mse >
                bv.best_training_mse * underfit_train_ratio
            ) AS training_error_exceeds_limit,
            (
                es.samples_per_parameter >= minimum_samples
            ) AS sample_adequacy_passed,
            (
                es.prediction_variance <= maximum_variance
            ) AS variance_passed
        FROM experiment_statistics es
        CROSS JOIN best_values bv
    ),
    decisions AS (
        SELECT
            assessed.*,
            CASE
                WHEN test_error_exceeds_limit
                     AND training_error_exceeds_limit
                    THEN 'UNDERFITTING'
                WHEN test_error_exceeds_limit OR NOT variance_passed
                    THEN 'OVERFITTING'
                ELSE 'GENERALIZES_WELL'
            END AS calculated_risk,
            (
                NOT test_error_exceeds_limit
                AND variance_passed
                AND sample_adequacy_passed
            ) AS policy_accepted
        FROM assessed
    )
    INSERT INTO model_decisions (
        experiment_id,
        candidate_id,
        risk_label,
        decision_status,
        samples_per_parameter,
        best_expected_test_mse,
        rationale
    )
    SELECT
        experiment_id,
        candidate_id,
        calculated_risk,
        CASE
            WHEN policy_accepted THEN 'ACCEPTED'
            ELSE 'REJECTED'
        END,
        samples_per_parameter,
        best_test_mse,
        CASE
            WHEN policy_accepted
                THEN 'Expected test error, prediction variance and sample adequacy satisfy policy.'
            ELSE CONCAT_WS(
                '; ',
                CASE
                    WHEN test_error_exceeds_limit
                        THEN 'Expected test error exceeds the allowed ratio.'
                END,
                CASE
                    WHEN NOT variance_passed
                        THEN 'Prediction variance exceeds the allowed maximum.'
                END,
                CASE
                    WHEN NOT sample_adequacy_passed
                        THEN 'Training observations per model parameter are insufficient.'
                END
            )
        END
    FROM decisions
    ON CONFLICT (experiment_id, candidate_id)
    DO UPDATE SET
        risk_label = EXCLUDED.risk_label,
        decision_status = EXCLUDED.decision_status,
        samples_per_parameter = EXCLUDED.samples_per_parameter,
        best_expected_test_mse = EXCLUDED.best_expected_test_mse,
        rationale = EXCLUDED.rationale,
        decided_at = clock_timestamp();

    UPDATE experiment_runs
    SET
        state = 'COMPLETED',
        completed_at = clock_timestamp()
    WHERE experiment_id = p_experiment_id;
END;
$$;


CREATE OR REPLACE FUNCTION fn_deployment_eligibility(
    p_experiment_id BIGINT
)
RETURNS TABLE (
    candidate_id BIGINT,
    candidate_name TEXT,
    polynomial_degree INTEGER,
    expected_test_mse NUMERIC,
    decision_status TEXT,
    rationale TEXT
)
LANGUAGE sql
STABLE
AS $$
    SELECT
        md.candidate_id,
        mc.candidate_name,
        mc.polynomial_degree,
        em.expected_test_mse,
        md.decision_status,
        md.rationale
    FROM model_decisions md
    JOIN model_candidates mc
        ON mc.candidate_id = md.candidate_id
    JOIN evaluation_metrics em
        ON em.experiment_id = md.experiment_id
       AND em.candidate_id = md.candidate_id
    JOIN experiment_runs er
        ON er.experiment_id = md.experiment_id
    WHERE md.experiment_id = p_experiment_id
      AND er.state = 'COMPLETED'
      AND md.decision_status = 'ACCEPTED'
    ORDER BY em.expected_test_mse, mc.polynomial_degree;
$$;


