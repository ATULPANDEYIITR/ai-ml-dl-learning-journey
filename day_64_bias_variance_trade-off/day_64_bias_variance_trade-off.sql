-- ============================================================================
-- 9. Retrieval and validation queries
-- ============================================================================

-- Inspect datasets and their experimental configurations.
SELECT
    dataset_id,
    dataset_name,
    sample_size,
    repetitions,
    noise_stddev,
    signal_description
FROM dataset_profiles
ORDER BY dataset_id;


-- Inspect experiment workflow states.
SELECT
    experiment_id,
    experiment_name,
    state,
    started_at,
    completed_at
FROM experiment_runs
ORDER BY experiment_id;


-- Validate the bias-variance decomposition for each recorded candidate.
SELECT
    experiment_id,
    candidate_id,
    bias_squared,
    prediction_variance,
    irreducible_noise,
    expected_test_mse,
    (
        bias_squared
        + prediction_variance
        + irreducible_noise
    ) AS independently_calculated_test_mse,
    (
        expected_test_mse =
        bias_squared + prediction_variance + irreducible_noise
    ) AS decomposition_valid
FROM evaluation_metrics
ORDER BY experiment_id, candidate_id;


-- Compare model complexity with training and expected test errors.
SELECT
    experiment_id,
    model_family,
    polynomial_degree,
    mean_training_mse,
    mean_bias_squared,
    mean_prediction_variance,
    mean_expected_test_mse,
    mean_generalization_gap
FROM v_complexity_curve
ORDER BY experiment_id, polynomial_degree;


-- Full evaluation and governance report.
SELECT
    candidate_name,
    polynomial_degree,
    ROUND(average_training_mse, 5) AS training_mse,
    ROUND(bias_squared, 5) AS bias_squared,
    ROUND(prediction_variance, 5) AS prediction_variance,
    ROUND(irreducible_noise, 5) AS irreducible_noise,
    ROUND(expected_test_mse, 5) AS expected_test_mse,
    ROUND(generalization_gap, 5) AS generalization_gap,
    risk_label,
    decision_status,
    rationale
FROM v_evaluation_report
ORDER BY polynomial_degree;


-- Aggregate accepted and rejected model counts.
SELECT
    er.experiment_name,
    md.decision_status,
    md.risk_label,
    COUNT(*) AS candidate_count,
    ROUND(AVG(em.expected_test_mse), 5) AS average_expected_test_mse,
    ROUND(AVG(em.prediction_variance), 5) AS average_prediction_variance
FROM model_decisions md
JOIN experiment_runs er
    ON er.experiment_id = md.experiment_id
JOIN evaluation_metrics em
    ON em.experiment_id = md.experiment_id
   AND em.candidate_id = md.candidate_id
GROUP BY
    er.experiment_name,
    md.decision_status,
    md.risk_label
ORDER BY
    er.experiment_name,
    md.decision_status,
    md.risk_label;


-- Deployment eligibility: only accepted candidates in completed experiments.
SELECT *
FROM fn_deployment_eligibility(
    (SELECT experiment_id
     FROM experiment_runs
     WHERE experiment_name = 'POLYNOMIAL_COMPLEXITY_COMPARISON')
);


-- ============================================================================
-- 10. Transaction and failure-handling demonstration
-- ============================================================================

-- This transaction demonstrates rollback of an invalid workflow action.
-- A completed experiment cannot be restarted.
SAVEPOINT before_invalid_transition;

DO $$
DECLARE
    v_experiment_id BIGINT;
BEGIN
    SELECT experiment_id
    INTO v_experiment_id
    FROM experiment_runs
    WHERE experiment_name = 'POLYNOMIAL_COMPLEXITY_COMPARISON';

    BEGIN
        CALL start_experiment(v_experiment_id);
    EXCEPTION
        WHEN OTHERS THEN
            RAISE NOTICE 'Expected workflow rejection: %', SQLERRM;
    END;
END;
$$;

ROLLBACK TO SAVEPOINT before_invalid_transition;
RELEASE SAVEPOINT before_invalid_transition;

-- The final state remains COMPLETED.
SELECT
    experiment_name,
    state,
    started_at,
    completed_at
FROM experiment_runs
WHERE experiment_name = 'POLYNOMIAL_COMPLEXITY_COMPARISON';

COMMIT;
